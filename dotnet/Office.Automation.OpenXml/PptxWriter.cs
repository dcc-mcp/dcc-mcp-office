    private static XElement ClrMap() =>
        new XElement(P + "clrMap",
            new XAttribute("bg1", "lt1"), new XAttribute("tx1", "dk1"), new XAttribute("bg2", "lt2"), new XAttribute("tx2", "dk2"),
            new XAttribute("accent1", "accent1"), new XAttribute("accent2", "accent2"), new XAttribute("accent3", "accent3"),
            new XAttribute("accent4", "accent4"), new XAttribute("accent5", "accent5"), new XAttribute("accent6", "accent6"),
            new XAttribute("hlink", "hlink"), new XAttribute("folHlink", "folHlink"));

    private static XElement Rect(int id, long x, long y, long cx, long cy, string fill)
    {
        var spPr = new XElement(P + "spPr",
            new XElement(A + "xfrm", new XElement(A + "off", new XAttribute("x", x), new XAttribute("y", y)), new XElement(A + "ext", new XAttribute("cx", cx), new XAttribute("cy", cy))),
            new XElement(A + "prstGeom", new XAttribute("prst", "rect"), new XElement(A + "avLst")),
            new XElement(A + "solidFill", new XElement(A + "srgbClr", new XAttribute("val", fill))),
            new XElement(A + "ln", new XElement(A + "noFill")));
        return new XElement(P + "sp", NonVisualProps(id, null, "Background", textBox: false), spPr, Style(), EmptyTxBody());
    }

    private static XElement Oval(int id, long x, long y, long cx, long cy, string fill)
    {
        var spPr = new XElement(P + "spPr",
            new XElement(A + "xfrm", new XElement(A + "off", new XAttribute("x", x), new XAttribute("y", y)), new XElement(A + "ext", new XAttribute("cx", cx), new XAttribute("cy", cy))),
            new XElement(A + "prstGeom", new XAttribute("prst", "ellipse"), new XElement(A + "avLst")),
            new XElement(A + "solidFill", new XElement(A + "srgbClr", new XAttribute("val", fill))),
            new XElement(A + "ln", new XElement(A + "noFill")));
        return new XElement(P + "sp", NonVisualProps(id, null, "Oval", textBox: false), spPr, Style(), EmptyTxBody());
    }

    private static XElement TextBox(int id, long x, long y, long cx, long cy, string text, double sizePt, string colorHex, bool bold, string align = "l")
    {
        var spPr = new XElement(P + "spPr",
            new XElement(A + "xfrm", new XElement(A + "off", new XAttribute("x", x), new XAttribute("y", y)), new XElement(A + "ext", new XAttribute("cx", cx), new XAttribute("cy", cy))),
            new XElement(A + "prstGeom", new XAttribute("prst", "rect"), new XElement(A + "avLst")),
            new XElement(A + "noFill"));
        var txBody = new XElement(P + "txBody",
            new XElement(A + "bodyPr", new XAttribute("wrap", "square")),
            new XElement(A + "lstStyle"));
        string alignVal = align switch { "ctr" => "ctr", "r" => "r", _ => "l" };
        foreach (var line in text.Split('\n'))
        {
            var para = new XElement(A + "p", new XAttribute("algn", alignVal));
            var run = new XElement(A + "r",
                new XElement(A + "rPr",
                    new XAttribute("lang", "zh-CN"),
                    new XAttribute("sz", (int)(sizePt * 100)),
                    bold ? new XAttribute("b", "1") : null,
                    new XElement(A + "solidFill", new XElement(A + "srgbClr", new XAttribute("val", colorHex))),
                    new XElement(A + "latin", new XAttribute("typeface", "Segoe UI")),
                    new XElement(A + "ea", new XAttribute("typeface", "Microsoft YaHei")),
                    new XElement(A + "cs", new XAttribute("typeface", "Segoe UI"))),
                new XElement(A + "t", line));
            para.Add(run);
            txBody.Add(para);
        }
        return new XElement(P + "sp", NonVisualProps(id, null, "TextBox", textBox: true), spPr, Style(), txBody);
    }

    private static XElement NonVisualProps(int id, string? placeholderType, string name, bool textBox = false)
    {
        var cNvSpPr = new XElement(P + "cNvSpPr");
        if (textBox)
        {
            cNvSpPr.Add(new XAttribute("txBox", "1"));
        }
        var nvSpPr = new XElement(P + "nvSpPr",
            new XElement(P + "cNvPr", new XAttribute("id", id), new XAttribute("name", name + " " + id)),
            cNvSpPr,
            new XElement(P + "nvPr"));
        if (placeholderType is not null)
        {
            var ph = new XElement(P + "ph", new XAttribute("type", placeholderType));
            if (placeholderType == "body")
            {
                ph.Add(new XAttribute("idx", "1"));
            }
            nvSpPr.Element(P + "nvPr")!.Add(ph);
        }
        return nvSpPr;
    }

    private static XElement BuildSpTree(params XElement[] children)
    {
        var spTree = new XElement(P + "spTree");
        spTree.Add(children);
        return spTree;
    }

    private static XElement[] GroupShapeProps(string id, long x, long y, long cx, long cy) =>
        new[]
        {
            new XElement(P + "nvGrpSpPr",
                new XElement(P + "cNvPr", new XAttribute("id", id), new XAttribute("name", "")),
                new XElement(P + "cNvGrpSpPr"),
                new XElement(P + "nvPr")),
            new XElement(P + "grpSpPr",
                new XElement(A + "xfrm",
                    new XElement(A + "off", new XAttribute("x", x), new XAttribute("y", y)),
                    new XElement(A + "ext", new XAttribute("cx", cx), new XAttribute("cy", cy)),
                    new XElement(A + "chOff", new XAttribute("x", 0), new XAttribute("y", 0)),
                    new XElement(A + "chExt", new XAttribute("cx", cx), new XAttribute("cy", cy)))),
        };

    private static XElement EmptyTxBody() => new XElement(P + "txBody",
        new XElement(A + "bodyPr", new XAttribute("rtlCol", "0"), new XAttribute("anchor", "ctr")),
        new XElement(A + "lstStyle"),
        new XElement(A + "p"));

    /// <summary>Required p:style block every sp in a slide carries.</summary>
    private static XElement Style() =>
        new XElement(P + "style",
            new XElement(A + "lnRef", new XAttribute("idx", "1"), new XElement(A + "schemeClr", new XAttribute("val", "accent1"))),
            new XElement(A + "fillRef", new XAttribute("idx", "3"), new XElement(A + "schemeClr", new XAttribute("val", "accent1"))),
            new XElement(A + "effectRef", new XAttribute("idx", "2"), new XElement(A + "schemeClr", new XAttribute("val", "accent1"))),
            new XElement(A + "fontRef", new XAttribute("idx", "minor"), new XElement(A + "schemeClr", new XAttribute("val", "lt1"))));

    private static XElement[] StyleLevels(int sizeCentipoints) =>
        Enumerable.Range(1, 9)
            .Select(level => new XElement(A + $"lvl{level}pPr",
                new XElement(A + "defRPr", new XAttribute("sz", sizeCentipoints * 100))))
            .ToArray();

    private static XElement[] DefaultTextStyle() =>
        Enumerable.Range(1, 9)
            .Select(level => new XElement(A + $"lvl{level}pPr",
                new XElement(A + "defRPr", new XAttribute("sz", 1800))))
            .ToArray();

    private static XElement EffectStyle() =>
        new XElement(A + "effectStyle",
            new XElement(A + "effectLst",
                new XElement(A + "outerShdw",
                    new XAttribute("blurRad", "0"), new XAttribute("dist", "0"), new XAttribute("dir", "5400000"), new XAttribute("rotWithShape", "0"),
                    new XElement(A + "srgbClr", new XAttribute("val", "000000")),
                    new XElement(A + "alpha", new XAttribute("val", "0")))));

    private static XElement[] FillStyleList() =>
        new[]
        {
            new XElement(A + "solidFill", new XElement(A + "schemeClr", new XAttribute("val", "phClr"))),
            new XElement(A + "solidFill", new XElement(A + "schemeClr", new XAttribute("val", "phClr"))),
            new XElement(A + "solidFill", new XElement(A + "schemeClr", new XAttribute("val", "phClr"))),
        };

    private static XElement[] LineStyleList() =>
        new[]
        {
            new XElement(A + "ln", new XAttribute("w", "9525"), new XElement(A + "solidFill", new XElement(A + "schemeClr", new XAttribute("val", "phClr")))),
            new XElement(A + "ln", new XAttribute("w", "9525"), new XElement(A + "solidFill", new XElement(A + "schemeClr", new XAttribute("val", "phClr")))),
            new XElement(A + "ln", new XAttribute("w", "9525"), new XElement(A + "solidFill", new XElement(A + "schemeClr", new XAttribute("val", "phClr")))),
        };

    private static long Emu(double inches) => (long)Math.Round(inches * EmuPerInch);

    private static PackagePart CreatePart(Package package, string uri, string contentType) =>
        package.CreatePart(new Uri(uri, UriKind.Relative), contentType, CompressionOption.Maximum);

    private static void WriteContent(PackagePart part, XElement content)
    {
        using var stream = part.GetStream();
        content.Save(stream);
    }
}
